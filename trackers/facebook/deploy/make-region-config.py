#!/usr/bin/env python3
"""Generate a standalone, single-region monitor config from master.toml.

The homelab worker runs master.toml's phase-1 city list. A SECOND account on the
same box must search a DIFFERENT region with no overlap, its own proxy, and its
own session — but everything else (the AI prompt, the buying criteria, the
twice-a-day start_at, the filters) has to stay identical to master, or the two
workers quietly diverge. So this takes master.toml and changes only three
things:

  * the phase-1 search_city / city_name / radius arrays  -> the named region's
  * [monitor].proxy_server                               -> ${<proxy_var>}
  * [monitor].storage_state_path                         -> /data/fb_state.json

Everything else is copied through untouched. Re-run it whenever master changes.

    python3 deploy/make-region-config.py rs_northeast PROXY_HOMELAB_NE \
        configs/homelab-ne.toml
"""

from __future__ import annotations

import shlex
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MASTER = ROOT / "configs" / "master.toml"


def replace_first_array(text: str, name: str, values: list, radius: bool = False) -> str:
    i = text.index(f"{name} = [")
    j = text.index("\n]", i) + 2
    if radius:
        body = ("    " + ", ".join(str(v) for v in values) + ",")
        rendered = f"{name} = [\n{body}\n]"
    else:
        rendered = f"{name} = [\n" + "\n".join(f'    "{v}",' for v in values) + "\n]"
    return text[:i] + rendered + text[j:]


def own_cities(spec: str) -> dict:
    """`slug=Name;slug=Name` -> a region-shaped block. A worker added beside a
    full fleet searches cities no region holds; the ERP edits them later."""
    pairs = [p.split("=", 1) for p in spec.split(";") if p.strip()]
    return {
        "search_city": [s.strip() for s, _ in pairs],
        "city_name": [n.strip() for _, n in pairs],
        "radius": [100] * len(pairs),
    }


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: make-region-config.py <region | 'slug=Name;slug=Name'> "
              "<proxy_env_var> <out.toml>", file=sys.stderr)
        return 2
    region, proxy_var, out = sys.argv[1], sys.argv[2], sys.argv[3]

    conf = tomllib.loads(MASTER.read_text())
    regions = conf.get("region", {})
    own = "=" in region
    if own:
        r = own_cities(region)
        region = "its own cities"
    elif region not in regions:
        print(f"error: region {region!r} not in master.toml "
              f"({', '.join(sorted(regions))})", file=sys.stderr)
        return 1
    else:
        r = regions[region]
    text = MASTER.read_text()

    # Phase-1 arrays -> this region's, zip-aligned.
    text = replace_first_array(text, "search_city", r["search_city"])
    text = replace_first_array(text, "city_name", r["city_name"])
    text = replace_first_array(text, "radius", r["radius"], radius=True)

    # Proxy: the phase-1 block references ${PROXY_HOMELAB}; point this worker at
    # its own dedicated endpoint instead.
    text = text.replace('proxy_server = "${PROXY_HOMELAB}"',
                        f'proxy_server = "${{{proxy_var}}}"', 1)
    # Absolute session path for the container (same reason as make-homelab-config).
    text = text.replace('storage_state_path = "configs/sessions/personal.json"',
                        'storage_state_path = "/data/fb_state.json"', 1)

    if own:
        scope = (f"# This worker starts on {', '.join(r['city_name'])}, through ${{{proxy_var}}}.\n"
                 f"# Its cities are set on the ERP's worker page (Edit cities), which the\n"
                 f"# console writes over this list. Set them before giving it an account:\n"
                 f"# until it has a login it searches nothing.\n\n")
    else:
        scope = (f"# This worker searches ONLY {region} ({len(r['search_city'])} centres),\n"
                 f"# through ${{{proxy_var}}}, so it does not overlap the homelab worker.\n\n")
    header = (f"# GENERATED by deploy/make-region-config.py {shlex.quote(sys.argv[1])} {proxy_var}\n"
              f"# from configs/master.toml — do not edit. Regenerate after changing master.\n"
              + scope)
    Path(out).write_text(header + text)

    # Prove the swap took and stayed aligned.
    check = tomllib.loads(Path(out).read_text())
    fb = check["marketplace"]["facebook"]
    assert len(fb["search_city"]) == len(fb["city_name"]) == len(fb["radius"]) == len(r["search_city"])
    assert check["monitor"]["proxy_server"] == f"${{{proxy_var}}}"
    print(f"wrote {out}: {len(fb['search_city'])} {region} centres, proxy ${{{proxy_var}}}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

const LOADERS: Record<string, () => Promise<Record<string, string>>> = {
  zh: () => import('./i18n.zh').then((m) => m.default),
};

// Resolves once `lang`'s table is readable from I18N. Safe to call repeatedly:
// the dynamic import is cached by the module system, and 'en' is already there.
export function loadDictionary(lang: Lang): Promise<void> {
  if (I18N[lang]) return Promise.resolve();
  const load = LOADERS[lang];
  if (!load) return Promise.resolve();
  return load().then((dict) => { I18N[lang] = dict; });
}

// For the handful of callers that need a string in a language other than the
// one currently rendering — e.g. confirming a language switch in the language
// the user just picked, before the provider has re-rendered.
export async function translateIn(lang: Lang, key: string): Promise<string> {
  await loadDictionary(lang);
  return I18N[lang]?.[key] ?? I18N.en?.[key] ?? key;
}

type Vars = Record<string, string | number>;

type LangCtx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Vars) => string;
};

const Ctx = createContext<LangCtx>({
  lang: 'en',
  setLang: () => {},
  t: (k) => k,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const { user, setLanguage } = useAuth();
  // Initialize from the user profile when it loads.
  const [lang, setLangLocal] = useState<Lang>('en');
  useEffect(() => { if (user?.language) setLangLocal(user.language); }, [user?.language]);

  // Non-English tables are separate chunks. Until one lands t() falls through
  // to English, which is what already happened on first paint: lang starts
  // 'en' and only moves once the user profile resolves.
  const [ready, setReady] = useState<Lang[]>(['en']);
  useEffect(() => {
    let live = true;
    loadDictionary(lang).then(() => {
      if (live) setReady((prev) => (prev.includes(lang) ? prev : [...prev, lang]));
    });
    return () => { live = false; };
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangLocal(l);
    if (user) setLanguage(l);
    document.documentElement.setAttribute('lang', l);
  };

  const t = (key: string, vars?: Vars) => {
    const dict = ready.includes(lang) ? I18N[lang] : undefined;
    let s = dict?.[key] || I18N.en?.[key] || key;
    // split/join, not replace: String.replace with a string pattern swaps only
    // the FIRST occurrence, so a template using one placeholder twice would
    // half-fill. No current key does, which is exactly why it is worth fixing
    // before one does.
    if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
    return s;
  };

  // Mirror the localised generic-error fallback into window so non-React
  // modules (lib/errorToast.ts) can surface translated copy.
  useEffect(() => {
    if (typeof window !== 'undefined') {
      window.__genericErrorMessage = t('generalErrorMsg');
    }
  }, [lang]);

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useT() {
  return useContext(Ctx);
}
